// Names and codes of Linux input events, as libevdev understands them.
//
// logid resolves `keys: ["KEY_…"]` and `axis: "REL_…"` with
// `libevdev_event_code_from_name` (src/logid/InputDevice.cpp), so the only
// authority on which names work is the system's libevdev — not the kernel
// header (e.g. the header alias KEY_HANGUEL is rejected by libevdev 1.13).
import 'generated/evdev_tables.g.dart';
import 'libevdev.dart';

/// Resolves evdev key (`EV_KEY`) and relative-axis (`EV_REL`) names.
abstract interface class EvdevCatalog {
  /// The catalog that matches the running system: libevdev itself when it
  /// can be loaded (exactly what logid does), else the generated tables.
  factory EvdevCatalog.system() =>
      LibevdevCatalog.open() ?? TableEvdevCatalog.instance;

  /// Code of an `EV_KEY` name (`KEY_*`, `BTN_*`), or null if not accepted.
  int? keyCode(String name);

  /// Code of an `EV_REL` name (`REL_*`), or null if not accepted.
  int? relativeAxisCode(String name);

  /// Canonical name of a key code (what libevdev prints), or null.
  String? keyName(int code);

  /// Canonical name of a relative-axis code, or null.
  String? relativeAxisName(int code);

  /// Every accepted key name (canonical names and supported aliases).
  Iterable<String> get keyNames;

  /// Every accepted relative-axis name.
  Iterable<String> get relativeAxisNames;
}

/// Catalog backed by the tables generated by `tool/generate.dart`
/// (see the versions recorded in `generated/evdev_tables.g.dart`).
final class TableEvdevCatalog implements EvdevCatalog {
  const TableEvdevCatalog._();

  /// The single instance.
  static const instance = TableEvdevCatalog._();

  @override
  int? keyCode(String name) => evdevKeyCodes[name];

  @override
  int? relativeAxisCode(String name) => evdevRelativeAxisCodes[name];

  @override
  String? keyName(int code) => evdevKeyCanonicalNames[code];

  @override
  String? relativeAxisName(int code) => evdevRelativeAxisCanonicalNames[code];

  @override
  Iterable<String> get keyNames => evdevKeyCodes.keys;

  @override
  Iterable<String> get relativeAxisNames => evdevRelativeAxisCodes.keys;
}
